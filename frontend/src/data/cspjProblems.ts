export function getProblemById(id: string) {
  return cspjProblems.find((problem) => problem.id === id) ?? null;
}

export function getProblemsByStage() {
  const map: Record<string, CspjProblem[]> = {};
  for (const problem of cspjProblems) {
    if (!map[problem.stage]) map[problem.stage] = [];
    map[problem.stage].push(problem);
  }
  return Object.entries(map).map(([stage, problems]) => ({ stage, problems }));
}
